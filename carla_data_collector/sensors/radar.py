"""
Provides implementation for radar sensor.
"""

import math
import weakref
from typing import TYPE_CHECKING, Optional

import carla

from carla_data_collector.sensors.base import Base
from carla_data_collector.utils import clamp

if TYPE_CHECKING:
    from carla_data_collector.world.world import World


class RadarSensor(Base):
    """
    Radar sensor handler.

    Avaliable attributes:
    - horizontal_fov: float
        Horizontal field of view in degrees, 30 by default.
    - points_per_second: int
        Points generated by all lasers per second, 1500 by default.
    - range: float
        Maximum distance to measure/raycast in meters, 100 by default.
    - vertical_fov: float
        Vertical field of view in degrees, 30 by default.
    """

    def __init__(
        self,
        name: str,
        parent_actor: carla.Actor,
        transform: Optional[carla.Transform] = None,
        **kwargs: dict,
    ):
        """
        Class for reading data from radar sensor.

        Parameters
        ----------
        name : str
            Name of the sensor.
        parent_actor : carla.Actor
            Carla's actor to whom sensor is attached.
        transform: Optional[carla.Transfrom]
            Translation and rotation of the sensor.
        **kwargs : dict
            Additonal parameters.

        """
        self._parent = parent_actor
        bound_x = 0.5 + self._parent.bounding_box.extent.x
        bound_z = 0.5 + self._parent.bounding_box.extent.z

        if kwargs.get("horizontal_fov", None) is None:
            kwargs["horizontal_fov"] = 35

        if kwargs.get("vertical_fov", None) is None:
            kwargs["vertical_fov"] = 20

        self.velocity_range = 7.5  # m/s

        transform = (
            carla.Transform(
                carla.Location(x=bound_x + 0.05, z=bound_z + 0.05),
                carla.Rotation(pitch=5),
            )
            if transform is None
            else transform
        )

        super().__init__(
            name, parent_actor, "sensor.other.radar", transform, **kwargs
        )
        self.debug = self._parent.get_world().debug
        self.detection = []

    def get_data(self, world: "World"):
        return {"points": self.detection}

    @staticmethod
    def _callback(
        weak_self: weakref.ReferenceType, radar_data: carla.RadarMeasurement
    ):
        self = weak_self()
        if not self:
            return

        current_rot = radar_data.transform.rotation
        self.detection = []
        for detect in radar_data:
            azi = math.degrees(detect.azimuth)
            alt = math.degrees(detect.altitude)

            # The 0.25 adjusts a bit the distance so the dots can
            # be properly seen
            fw_vec = carla.Vector3D(x=detect.depth - 0.25)
            carla.Transform(
                carla.Location(),
                carla.Rotation(
                    pitch=current_rot.pitch + alt,
                    yaw=current_rot.yaw + azi,
                    roll=current_rot.roll,
                ),
            ).transform(fw_vec)

            self.detection.append((fw_vec.x, fw_vec.y, fw_vec.z))

            norm_velocity = (
                detect.velocity / self.velocity_range
            )  # range [-1, 1]
            r = int(clamp(0.0, 1.0, 1.0 - norm_velocity) * 255.0)
            g = int(clamp(0.0, 1.0, 1.0 - abs(norm_velocity)) * 255.0)
            b = int(abs(clamp(-1.0, 0.0, -1.0 - norm_velocity)) * 255.0)
            self.debug.draw_point(
                radar_data.transform.location + fw_vec,
                size=0.075,
                life_time=0.06,
                persistent_lines=False,
                color=carla.Color(r, g, b),
            )
